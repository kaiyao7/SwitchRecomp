#!/usr/bin/env python3
"""Generate SPIR-V compute shader artifacts (Phase 4-1).

Compiles tests/fixtures/shaders/add1.comp into:
  tests/fixtures/shaders/add1.spv      - raw SPIR-V blob (kept for inspection)
  src/gpu/generated/add1_spv.h         - embedded blob as a uint32 array,
                                         consumed by the internal
                                         ComputeExecutor Vulkan module

Compiler discovery:
  1. --glslang PATH / --glslc PATH command line overrides
  2. glslangValidator / glslc found on PATH

The script is idempotent: repeated runs regenerate byte-identical outputs.
When no compiler is available:
  - existing .spv/.h outputs are kept and the build continues using them;
  - if neither exists, a clear MISSING notice is printed (the dependent
    tests are compiled to skip).
"""

import argparse
import os
import shutil
import subprocess
import sys

SHADER_NAME = "add1.comp"
WORDS_PER_LINE = 12


def find_compiler(args):
    """Return (kind, path) for the first usable shader compiler."""
    if args.glslang and os.path.isfile(args.glslang):
        return "glslang", args.glslang
    if args.glslc and os.path.isfile(args.glslc):
        return "glslc", args.glslc
    glslang = shutil.which("glslangValidator")
    if glslang:
        return "glslang", glslang
    glslc = shutil.which("glslc")
    if glslc:
        return "glslc", glslc
    return None, None


def compile_shader(kind, compiler, source_path, spv_path):
    if kind == "glslang":
        cmd = [compiler, "-V", source_path, "-o", spv_path]
    else:
        cmd = [compiler, "-fshader-stage=comp", source_path, "-o", spv_path]
    print("compiling {} ({}): {}".format(SHADER_NAME, kind,
                                         " ".join(cmd)))
    subprocess.run(cmd, check=True)


def write_header(spv_bytes, header_path):
    if len(spv_bytes) % 4 != 0:
        raise RuntimeError("SPIR-V blob size is not a multiple of 4 bytes")
    words = [int.from_bytes(spv_bytes[i:i + 4], "little")
             for i in range(0, len(spv_bytes), 4)]

    lines = []
    lines.append("// AUTO-GENERATED by scripts/gen_shaders.py.")
    lines.append("// Do not edit; regenerate with scripts/gen_shaders.py.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace sr::gpu {")
    lines.append("")
    lines.append("// Embedded SPIR-V for tests/fixtures/shaders/add1.comp")
    lines.append("// (compute: increments every uint element by one).")
    lines.append("inline const std::uint32_t kAdd1Spv[] = {")
    for start in range(0, len(words), WORDS_PER_LINE):
        chunk = words[start:start + WORDS_PER_LINE]
        body = ", ".join("0x{:08X}".format(w) for w in chunk)
        comma = "," if start + WORDS_PER_LINE < len(words) else ""
        lines.append("    {}{}".format(body, comma))
    lines.append("};")
    lines.append("")
    lines.append("// Size of the embedded SPIR-V blob in bytes.")
    lines.append("inline const std::size_t kAdd1SpvSize = sizeof(kAdd1Spv);")
    lines.append("")
    lines.append("} // namespace sr::gpu")
    lines.append("")

    os.makedirs(os.path.dirname(header_path), exist_ok=True)
    with open(header_path, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote {} ({} bytes, {} words)".format(header_path,
                                                 len(spv_bytes), len(words)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--glslang", help="path to glslangValidator")
    parser.add_argument("--glslc", help="path to glslc")
    args = parser.parse_args()

    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_root = os.path.dirname(script_dir)
    source_path = os.path.join(project_root, "tests", "fixtures",
                               "shaders", SHADER_NAME)
    spv_path = os.path.join(project_root, "tests", "fixtures",
                            "shaders", "add1.spv")
    header_path = os.path.join(project_root, "src", "gpu", "generated",
                               "add1_spv.h")

    kind, compiler = find_compiler(args)
    if kind is None:
        have_spv = os.path.isfile(spv_path)
        have_header = os.path.isfile(header_path)
        if have_spv and have_header:
            print("no shader compiler found; keeping existing {} and {}"
                  .format(spv_path, header_path))
            return 0
        print(
            "MISSING: no glslangValidator/glslc found and prebuilt artifacts "
            "are absent ({}: {}, {}: {}). Compute dispatch tests will skip."
            .format(spv_path, "present" if have_spv else "absent",
                    header_path, "present" if have_header else "absent"))
        return 0

    try:
        compile_shader(kind, compiler, source_path, spv_path)
        with open(spv_path, "rb") as f:
            spv_bytes = f.read()
        write_header(spv_bytes, header_path)
    except (subprocess.CalledProcessError, OSError, RuntimeError) as exc:
        print("ERROR: shader generation failed: {}".format(exc),
              file=sys.stderr)
        return 2

    print("wrote {}".format(spv_path))
    return 0


if __name__ == "__main__":
    sys.exit(main())
